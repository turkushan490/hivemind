// Bakes the built web UI (web/dist) into server/src/web-assets.generated.ts, so the Windows .exe is one file.
// Run after `npm run build -w web`, before bundling the exe. Node-only, no dependencies.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webDist = join(here, '..', '..', 'web', 'dist');
const out = join(here, '..', 'src', 'web-assets.generated.ts');

/** Every file under web/dist, as published paths relative to it. */
function walk(dir) {
  const files = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else files.push(full);
  }
  return files;
}

const files = walk(webDist);
const map = {};
let bytes = 0;
for (const full of files) {
  const rel = relative(webDist, full).split('\\').join('/');
  const data = readFileSync(full);
  bytes += data.length;
  map[rel] = data.toString('base64');
}
// A build id from the content, so the exe re-extracts the UI only when it changed.
const buildId = String(files.length) + '-' + bytes + '-' + Date.now().toString(36);

const body =
  '// GENERATED by scripts/embed-web.mjs — do not edit. The web UI baked into the Windows .exe.\n' +
  `export const webAssets: Record<string, string> = ${JSON.stringify(map)};\n` +
  `export const webBuildId = ${JSON.stringify(buildId)};\n`;
writeFileSync(out, body);
console.log(`Embedded ${files.length} web files (${(bytes / 1024 / 1024).toFixed(1)} MB) into ${relative(process.cwd(), out)}`);
