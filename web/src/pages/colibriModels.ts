/**
 * Every model family colibri runs (its README and docs/gguf.md, v2.1.0), for Settings → Colibri → Library.
 * - catalog: colibri's ready-made download (one click, its own catalog id);
 * - gguf: what to search on Hugging Face for GGUF files of it (coli import reads them in place);
 * - convert: only runs after a conversion with PyTorch, which HiveMind can't do (yet).
 * Speeds are colibri's own measurements, on its test machines.
 */
export type LibTag = 'chat' | 'vision' | 'tools' | 'thinking' | 'code' | 'decision' | 'image';

export interface LibModel {
  id: string;
  name: string;
  /** "35B · 3B active" */
  params: string;
  about: string;
  tags: LibTag[];
  /** Download size as text, and the smallest in GB (for the size filter). */
  size: string;
  minGb: number;
  /** RAM colibri needs at least, in GB (for the fit label). */
  ramGb: number;
  /** colibri's engine for it (must be in the image). */
  engine: string;
  /** The original model on Hugging Face. */
  hf: string;
  catalog?: string;
  gguf?: string;
  convert?: boolean;
  /** A family in many sizes: one button per size, each searching its own GGUF files (Q4 size in GB for the fit label). */
  sizes?: { label: string; query: string; gb: number }[];
  speed?: string;
  license?: string;
}

