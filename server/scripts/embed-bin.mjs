// Bakes the Windows whisper.cpp binary (server/whisper-bin/*) into server/src/whisper-bin.generated.ts, so the .exe
// carries its own speech engine. Run in CI after the Windows whisper build, before bundling the exe. Node-only.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const binDir = join(here, '..', 'whisper-bin');
const out = join(here, '..', 'src', 'whisper-bin.generated.ts');

const map = {};
let bytes = 0;
if (existsSync(binDir)) {
  for (const name of readdirSync(binDir)) {
    const full = join(binDir, name);
    if (!statSync(full).isFile()) continue;
    const data = readFileSync(full);
    bytes += data.length;
    map[name] = data.toString('base64');
  }
}
const buildId = Object.keys(map).length ? `${Object.keys(map).length}-${bytes}` : '';
const body =
  '// GENERATED by scripts/embed-bin.mjs — do not edit. The Windows whisper.cpp binary baked into the .exe.\n' +
  `export const whisperBin: Record<string, string> = ${JSON.stringify(map)};\n` +
  `export const whisperBinId = ${JSON.stringify(buildId)};\n`;
writeFileSync(out, body);
console.log(`Embedded ${Object.keys(map).length} whisper file(s) (${(bytes / 1024 / 1024).toFixed(1)} MB) into ${relative(process.cwd(), out)}`);
